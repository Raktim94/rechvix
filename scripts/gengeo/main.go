//go:build ignore

// gengeo regenerates internal/platform/money/iso4217_gen.go and
// internal/platform/geo/countries_gen.go.
//
//	go run scripts/gengeo/main.go <path to SIX list-one.xml>
//
// Currency codes, numeric codes and minor units come from the ISO 4217
// maintenance agency's list-one.xml
// (https://www.six-group.com/en/products-services/financial-information/data-services/iso-4217-currency-codes.html).
// Countries (ISO 3166-1 alpha-2), English names and each country's default
// currency come from the CLDR data bundled in golang.org/x/text.
package main

import (
	"encoding/xml"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"

	"golang.org/x/text/currency"
	"golang.org/x/text/language"
	"golang.org/x/text/language/display"
)

type entry struct {
	Name   string `xml:"CcyNm"`
	Code   string `xml:"Ccy"`
	Num    string `xml:"CcyNbr"`
	Minors string `xml:"CcyMnrUnts"`
}
type doc struct {
	Published string  `xml:"Pblshd,attr"`
	Entries   []entry `xml:"CcyTbl>CcyNtry"`
}

func main() {
	raw, err := os.ReadFile(os.Args[1])
	check(err)
	var d doc
	check(xml.Unmarshal(raw, &d))

	type ccy struct {
		Code, Name, Num string
		Minor           int
	}
	seen := map[string]ccy{}
	for _, e := range d.Entries {
		if e.Code == "" || e.Minors == "N.A." || e.Minors == "" {
			continue // funds codes, precious metals, XXX, XTS: not transactional currencies
		}
		var m int
		_, err := fmt.Sscanf(e.Minors, "%d", &m)
		check(err)
		seen[e.Code] = ccy{e.Code, strings.TrimSpace(e.Name), e.Num, m}
	}
	codes := make([]string, 0, len(seen))
	for c := range seen {
		codes = append(codes, c)
	}
	sort.Strings(codes)

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by scripts/gengeo from ISO 4217 amendment published %s. DO NOT EDIT.\n\npackage money\n\n", d.Published)
	b.WriteString("// CurrencyInfo describes one ISO 4217 currency.\ntype CurrencyInfo struct {\n\tCode, Name, Numeric string\n\tMinorDigits int32\n}\n\n")
	b.WriteString("// ISO4217 lists every transactional ISO 4217 currency, sorted by code.\nvar ISO4217 = []CurrencyInfo{\n")
	for _, c := range codes {
		x := seen[c]
		fmt.Fprintf(&b, "\t{%q, %q, %q, %d},\n", x.Code, x.Name, x.Num, x.Minor)
	}
	b.WriteString("}\n\nfunc init() {\n\tfor _, c := range ISO4217 {\n\t\tif _, ok := minorUnits[c.Code]; !ok {\n\t\t\tminorUnits[c.Code] = c.MinorDigits\n\t\t}\n\t}\n}\n")
	write("internal/platform/money/iso4217_gen.go", b.String())

	// Countries.
	type country struct{ Code, Name, Currency string }
	var cs []country
	namer := display.English.Regions()
	for a := 'A'; a <= 'Z'; a++ {
		for z := 'A'; z <= 'Z'; z++ {
			code := string([]rune{a, z})
			r, err := language.ParseRegion(code)
			if err != nil || !r.IsCountry() || r.String() != code || !iso3166[code] {
				continue
			}
			cur := ""
			if u, ok := currency.FromRegion(r); ok {
				cur = u.String()
			}
			// ISO 4217 wins over CLDR where they disagree (checked against the
			// country entries of the 2026-09-17 amendment): CLDR lags on
			// retired currencies (BGN, HRK, SLL, VEF) and picks USD for Zimbabwe.
			if o, ok := isoOverrides[code]; ok {
				cur = o
			}
			if _, known := seen[cur]; !known {
				cur = ""
			}
			if cur == "" {
				fmt.Fprintf(os.Stderr, "note: %s %s has no default currency\n", code, namer.Name(r))
			}
			cs = append(cs, country{code, namer.Name(r), cur})
		}
	}
	var g strings.Builder
	fmt.Fprintf(&g, "// Code generated by scripts/gengeo (CLDR via golang.org/x/text; currencies checked against ISO 4217 %s). DO NOT EDIT.\n\npackage geo\n\n", d.Published)
	g.WriteString("// Country is an ISO 3166-1 country or territory.\ntype Country struct {\n\tCode, Name, DefaultCurrency string\n}\n\n// Countries lists ISO 3166-1 alpha-2 countries, sorted by code.\nvar Countries = []Country{\n")
	for _, c := range cs {
		fmt.Fprintf(&g, "\t{%q, %q, %q},\n", c.Code, c.Name, c.Currency)
	}
	g.WriteString("}\n")
	write("internal/platform/geo/countries_gen.go", g.String())
	fmt.Printf("%d currencies, %d countries\n", len(codes), len(cs))
}

func write(path, src string) {
	out, err := format.Source([]byte(src))
	check(err)
	check(os.WriteFile(path, out, 0o644))
}
func check(err error) {
	if err != nil {
		panic(err)
	}
}

// iso3166 is the ISO 3166-1 alpha-2 assignment list (249 codes) plus XK
// (Kosovo: user-assigned, but used by the EU, IMF and tax authorities). CLDR
// also carries legacy codes (YU, SU, AN, ...) and exceptional reservations
// (EU, UN, AC, ...) that must not appear as selectable countries.
var iso3166 = func() map[string]bool {
	const codes = "AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ " +
		"CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR " +
		"GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP " +
		"KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ " +
		"NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW " +
		"SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ " +
		"UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS YE YT ZA ZM ZW"
	m := map[string]bool{"XK": true}
	for _, c := range strings.Fields(codes) {
		m[c] = true
	}
	if len(m) != 250 {
		panic(fmt.Sprintf("iso3166 allowlist has %d entries, want 250 (249 + XK)", len(m)))
	}
	return m
}()

var isoOverrides = map[string]string{"BG": "EUR", "HR": "EUR", "SL": "SLE", "VE": "VES", "ZW": "ZWG", "CW": "XCG", "SX": "XCG", "MR": "MRU"}
